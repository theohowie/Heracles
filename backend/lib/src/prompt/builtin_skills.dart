import 'package:dart_agent_core/dart_agent_core.dart';

/// 内置技能的**唯一清单**（组装层读这里；测试断言也钉这里）。
List<Skill> builtinSkills() => [
      _BuiltinSkill(
        name: 'verify-loop',
        description: '构建-验证-修复循环：改完代码/配置后自动验证，失败进修复循环',
        systemPrompt: '''
## 技能：verify-loop（构建-验证-修复循环）

**何时用**：你修改了代码、配置或补丁之后；用户要求"跑通/修好/验证"。

**工作流（每轮都按这个走）**：
1. **验证**：优先用项目里已有的验证手段（构建命令、测试、`run_shell_command`）；
   没有现成手段就用最轻的核对（读回改过的文件、跑一次最小复现）。
2. **判定**：验证输出里找**具体失败证据**（报错原文、失败的测试名），
   不要凭感觉判定"应该好了"。
3. **修复**：定位到根因再改 —— 一次只改一个可疑点，改完**立刻回到第 1 步**。
4. **收尾**：连续 3 次修复仍失败 ⇒ 停下，向用户如实报告：
   已试过什么、卡在哪个证据上、建议下一步。**不许宣称"修好了"而没有验证证据。**
''',
      ),
      _BuiltinSkill(
        name: 'root-cause-first',
        description: '先诊断再动手：bug 修复类任务先读代码定位根因，再改',
        systemPrompt: '''
## 技能：root-cause-first（先诊断再动手）

**何时用**：修 bug、修报错、"不对劲"类任务。

**工作流**：
1. **复现/观察**：先拿到完整证据（报错原文、相关日志、复现步骤）；
   拿不到就先问用户或用工具取。
2. **定位**：用 grep_files/read_file 读相关代码，找到**触发路径** ——
   从报错点往上追到"哪一行做出了错误决定"。
3. **假设**：用一句话写下"我认为根因是 X，证据是 Y"。
4. **改**：只改根因处；顺手修别的症状前先说明理由。
5. **验证**：确认原证据消失（接 verify-loop 技能）。

**红线**：没有证据支持的"修复"不许动手 —— 那是猜，猜错会把问题改没影。
''',
      ),
      _BuiltinSkill(
        name: 'small-steps',
        description: '小步修改：多文件/大改动拆成一次一件，改完即验',
        systemPrompt: '''
## 技能：small-steps（小步修改）

**何时用**：改动跨多个文件、或单处改动超过 ~50 行、或拿不准影响面。

**工作流**：
1. **拆步**：把改动列成 `write_todos`，每步 = 一个文件/一个关注点。
2. **一步一件**：每步用 `edit`/`apply_patch`（不整文件重写），
   保持原有代码风格与结构。
3. **步内即验**：每步完成立刻核对（读回 / 构建该文件），
   错了当场修 —— 不攒到最后一起验。
4. **顺序**：先改被依赖的，再改依赖方；每步之后影响面应当是收敛的。

**红线**：禁止为了"快"把三个文件的改动揉进一次 write_file ——
出了问题你分不清是哪一步引入的。
''',
      ),
    ];

class _BuiltinSkill extends Skill {
  _BuiltinSkill({
