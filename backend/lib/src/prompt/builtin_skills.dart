///
/// ## 这是什么
///
/// 重复性流程沉淀为**提示型技能**：名称 + 触发条件 + 工作流，平时只在
/// 系统提示里占一行目录（渐进披露），模型按任务用 `activate_skills`
/// 按需加载全文 —— 这是教材第 9 章的标准形态，也与 Claude Code 的
/// Skill 机制同构。
///
/// ## 为什么只有这三条
///
/// 只沉淀**跨任务复用、且模型经常自发做错**的流程。每条都对应
/// 对照表里的一个真实欠账：
///
/// · `verify-loop` ↔ H3/K2（自验证循环）：架构级管线没有，但"改完必验、
///   失败进修复循环"的**流程纪律**可以用技能承载 —— 模型激活后每一轮
///   都看得见全文，比散在 system prompt 里的一句话强得多；
/// · `root-cause-first` ↔ K1（代码理解先于修改）；
/// · `small-steps` ↔ K3（小步修改）。
///
/// ## 刻意不做的
///
/// · **不设 `forceActivate`**：三条都是"按需激活"——强塞全文等于回到
///   "教练式 system prompt"的老路（`system_prompt.dart` 文件头记过教训）；
/// · 不做代码型技能 / 目录模式（`skillDirectoryPaths`）：等有真实的
///   用户侧技能需求再说，现在只有内置三条。
