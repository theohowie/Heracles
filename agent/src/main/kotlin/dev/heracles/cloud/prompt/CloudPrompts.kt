package dev.heracles.cloud.prompt

/**
 * **云端系统提示词**（`CloudAgentPipeline`，模块四）。
 *
 * ## 它替代了什么（旧 "教练三连"）
 *
 * 旧 `AgentLoop.TOOL_PROTOCOL_CLOUD`（`AgentLoop.kt:2770-2822`）+ 原生轨协议
 * （`:2846-2872`）里有三句**明确为 4B 写的话**：
 *
 * ```
 * - 计划要给 2 步以上
 * - 给出计划后，一次只做当前那一步
 * - 单个文件很大（超过约 3000 字符）时分几次写
 * ```
 *
 * 为什么这三句对云端强模型是**反向教练**（这个词是仓库自己在 `AgentLoop.kt:2757`
 * 定义的：「那句对 4B 是必要的护栏，对强模型是反向教练」）：
 *
 * | 指令 | 对 4B | 对 GPT-6 / Opus 5.5 |
 * |---|---|---|
 * | 计划 ≥ 2 步 | 防它不给计划 | 单步任务是真实存在的 ⇒ 逼它**凑假步骤**，污染计划 |
 * | 一次只做一步 | 防它一次做太多出错 | 与「可以一次发多个调用」**正面矛盾**；白跑多轮 |
 * | 超 3000 字符分段写 | 4B 输出量级确实小 | 对大模型是**几行代码** ⇒ 制造半截文件 |
 *
 * ## 新版原则：**只给事实与环境，不给行为限制**
 *
 * 大模型不需要被告知"怎么做"，它需要知道：
 * 1. 它在什么环境里（Android、有工作区、有 shell、有审批）
 * 2. 工具怎么用（**由 JSON Schema 表达**，不靠自然语言复述）
 * 3. 边界在哪里（不编工具名、不猜文件内容、危险操作需审批）
 *
 * ⇒ 整份提示词从 ~760 字降到 ~300 字，且**没有一句限制它的输出形式**。
 */
object CloudPrompts {

    /**
     * 基础系统提示 —— 环境与边界。**不含任何行为教练**。
     *
     * ## ★ 2026-10-21 真机修正：加了两条**效率**引导
     *
     * 真机实测（`deepseek-v4.1-flash-1017`，任务只是"列出工作区文件"）：
     * 模型跑了 **22 轮**，在 `list_files` → `find_files` → `grep_files` 之间反复试探。
     *
     * 这不是"模型不行"，而是**提示词没给它停止条件**：
     * 旧提示词只说"看不清就先读"，没说"**看够了就答**"。
     * 大模型有完美主义倾向 ⇒ 会一直"再确认一下"。
     *
     * ⚠️ 注意这**不是**"教练"（限制它怎么做），而是给**事实性约束**：
     * · 回答简单问题不需要穷举整个仓库
     * · 拿到了需要的信息就停
     *
     * 与旧提示词的区别：旧的是"**你必须**分步/一次只做一步/3000 字符分段"
     * （限制手段），这里说的是"**什么时候算够了**"（给出停止条件）。
     */
    val SYSTEM = """
你是 Heracles，一个运行在 Android 手机上的开发智能体。

## 你的环境
- 你有一个**工作区**（用户选定的文件夹），所有路径都相对于它
- 你可以读写文件、执行 shell 命令、构建与逆向 Android APK
- 你可以联网抓取网页、读取工作区里的图片
- 部分操作需要用户审批（取决于权限档位），被拒时你会收到明确告知

## 你的工作方式
你拥有完整的规划与执行能力，请**自主决定**怎么做：
- 需要规划就规划，一步够用就一步做完
- 相关操作可以合并；互不依赖的调用可以**一次发起多个**
- 文件可以一次性写完整，不需要为了"分段"而分段
- 看不清内容时先读，不要凭猜测修改

## 什么时候该停
**任务够简单就直接答。** 只在需要时才扩大探索范围：
- 用户问"有哪些文件"⇒ 看一次目录就够，不必再 grep 整个仓库
- 拿到了回答问题所需的信息 ⇒ 立刻给出答案，不要"再确认一下"
- 同一个信息不要用多个工具反复交叉验证 —— 除非你怀疑上一步真的错了
- 你已经明显在原地打转（连续用不同工具查同一件事）⇒ 停下来，说明你查到了什么

## 唯一必须遵守的边界
- 只能用提供的工具；不要编造工具名
- 不要猜测文件内容——先读再改
- 工具返回失败时，如实向用户说明，不要宣称成功

工具的参数格式由 JSON Schema 定义（见 tools 字段），按 schema 填写即可。
""".trim()

    /**
     * 工具调用参数错误后的**纠正提示**。
     *
     * ## 与旧版的关键区别
     *
     * 旧版（`AgentLoop.kt:2143-2153`）会教模型"三种顶层形状"（`{"tool":…}` / `{"plan":…}` /
     * `{"final":…}`），并加一句「只输出其中一种，不要任何解释」。那是**文本轨方言**，
     * 在原生 function calling 下完全多余 —— 而且"不要任何解释"是明确的反向教练。
     *
     * 新版只做一件事：**把 Schema 校验的具体错误告诉它**，然后让它重试。
     * 大模型看到 "参数 offset 类型错：期望 integer，实际是 string" 一轮就能改对。
     *
     * @param detail 来自 `CloudToolValidator` 的具体错误
     */
    fun schemaCorrection(detail: String): String = """
上一次工具调用的参数不符合 Schema，未执行。

具体错误：$detail

请按 Schema 修正参数后重新发起调用。
""".trim()

    /**
     * 上下文压缩摘要提示。
     *
     * 与旧版（`AgentLoop.kt:1228-1232`）语义相同（保留什么），
     * 但**输出预算**必须 ≥ 4096（旧版 1024 会让思考吃光预算，见
     * `ContextManager.MIN_SUMMARY_OUTPUT_TOKENS`）。
     */
    val SUMMARY = """
以下是你与用户此前的完整交互记录。请压缩成一段**供你自己后续使用**的摘要。

必须保留：
- 任务目标与当前进展
- 已创建/修改的文件路径及各自状态
- 关键结论、数据、错误信息
- 尚未完成的步骤

不要寒暄，直接输出摘要正文。
""".trim()

    /**
     * 达到工具调用预算/轮次上限时的收尾提示 —— **如实说"没做完"**。
     *
     * 旧实现在循环硬停时写「**判定任务已完成**并停止」（`AgentLoop.kt:1589-1622`）——
     * 那是**替模型下结论**，正是"谎称已完成"的温床。新版如实报"预算用尽，任务未完成"。
     */
    fun budgetExhausted(reason: String): String = """
已停止：$reason。

请向用户如实说明：任务**未完成**，以及你做到哪一步、还差什么。
不要宣称任务已完成。
""".trim()
}
