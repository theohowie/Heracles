/// **上下文长度解析**（2026-10-14，推翻第二版重做）。
///
/// ## 两版都错，用户的批评逐步逼近真相
///
/// | 版本 | 做法 | 用户的批评 |
/// |---|---|---|
/// | 1 | 让用户在编辑页**手填** | 「1M 就是 1M，**不用自己选的**，你觉得这合理吗？」 |
/// | 2 | 我**凭印象编**一张内置表 | 「你确定你查的是对的？deepseek-flash 是 1M，kimi-k3 也是 1M，结果呢？」 |
///
/// **第二版实测错了 2/25**：
///
/// | 模型 | 我编的 | 服务端真实值 |
/// |---|---|---|
/// | `deepseek-flash` | 128K ❌ | **1,000,000** |
/// | `kimi-k3` | 256K ❌ | **1,048,576** |
///
/// ## 结论：内置表这条路本身就是错的
///
/// 理由（不是"我没编好"，是方法不成立）：
/// 1. 中转站的模型名是**它自己起的别名**（`deepseek-flash` ≠ 官方
///    `deepseek-chat`），同一名字在不同中转站能力**可能不同**
/// 2. 模型迭代快，任何快照表都会过期
/// 3. 服务端**明明提供了权威值**（实测：基元律动 `GET /api/models`
///    返回 `contextWindow` 字段，29 个模型全有）
///
/// **能问就不要猜。**
///
/// ## 本实现：服务端优先 + 诚实兜底
///
/// 1. **服务端上报的能力**（`/v1/models` 或中转站的模型 API）—— 用它
/// 2. 拿不到 → 用**保守兜底值**（本地 4096 / 云端 128K），
///    并在 UI 明确标注「未从服务端获取」—— **不假装知道**
///
/// ## 为什么不再内置模型名表
///
/// 保留"少量**确知**的值"是有价值的，但**不再按厂商名猜** ——
/// 那正是错的地方。
///
/// ⚠️ **2026-10-18（ADR-035 S4）**：原先这里还有一张"本地模型确定值"表
/// （`qwen3.5-4b` → 4096）。本地后端已整体删除 ⇒ **那张表连同
/// `isLocal` 这条分支一起删掉**（`resolve()` 的本地分支已不可达）。
/// 今天**只剩云端一条路**：服务端上报值优先，拿不到就诚实兜底。
library;

class ModelContextTable {
  const ModelContextTable._();

  /// **解析上下文长度**（云端一条路）。
  ///
  /// @param fromServer 服务端上报值（**权威**）；`null` = 未获取
  /// @param modelName 模型名（**只用于日志/诊断**，不再参与查表）
  /// @param fallback 诚实兜底（今天恒为云端值）
  static int resolve({
    int? fromServer,
    required String modelName,
    required int fallback,
  }) {
    // ① 服务端说的是权威（实测：`contextWindow` 由 `/api/models` 提供）
    if (fromServer != null && fromServer > 0) return fromServer;
    // ② 拿不到 → 诚实兜底（UI 会标注"未从服务端获取"）
    return fallback;
  }
}
